@Test func basicPairs() {
    let p = Pluralize()
    for pair in pairs {
        #expect(p.plural(pair.single) == pair.plural)
        #expect(p.singular(pair.plural) == pair.single)
        #expect(p.isPlural(pair.plural))
        #expect(p.isSingular(pair.single))
    }
}

@Test func countPicksSingularOrPlural() {
    let p = Pluralize()
    for pair in pairs {
        #expect(p.count(pair.plural, 1) == pair.single)
        #expect(p.count(pair.single, 5) == pair.plural)
    }
}

@Test func countInclusivePrefixesTheNumber() {
    let p = Pluralize()
    #expect(p.count("test", 1, inclusive: true) == "1 test")
    #expect(p.count("test", 2, inclusive: true) == "2 tests")
}

@Test func casePreservation() {
    let p = Pluralize()
    let cases: [(String, String)] = [
        ("cow", "cows"), ("Cow", "Cows"), ("COW", "COWS"),
    ]
    for (single, plural) in cases {
        #expect(p.plural(single) == plural)
        #expect(p.singular(plural) == single)
    }
}

@Test func customRules() {
    var p = Pluralize()

    // Irregular.
    p.addIrregularRule(single: "canadia", plural: "canadensis")
    #expect(p.plural("canadia") == "canadensis")
    #expect(p.singular("canadensis") == "canadia")

    // Uncountable.
    p.addUncountableRule("paper")
    #expect(p.plural("paper") == "paper")

    // Plural rule.
    p.addPluralRule("gex$", replacement: "gexii")
    #expect(p.plural("regex") == "regexii")

    // Singular rule.
    p.addSingularRule("s$", replacement: "")
    #expect(p.singular("appleS") == "apple")
}
